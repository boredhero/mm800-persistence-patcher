#!/usr/bin/env python3
import argparse
import random
from pathlib import Path

from custom_animation import CanonicalAnimation, CodecUnavailable, Entry, decode_animation
from animation_brightness import ALL_CODECS as CODECS, encode_brightness_candidate, load_animation_document, optimize_animation_document


def model(frames, durations, loop=True):
    palette = []
    for frame in frames:
        for index in range(0, 45, 3):
            color = frame[index:index + 3]
            if color not in palette:
                palette.append(color)
    entries = [Entry(index % len(frames), duration) for index, duration in enumerate(durations)]
    total = sum(durations) * 34
    return CanonicalAnimation(frames, entries, palette, loop, "hold", [], len(entries), total, total)


def fill(rgb):
    return bytes.fromhex(rgb) * 15


def scenarios():
    off = fill("000000")
    purple = fill("8000ff")
    blue = fill("0000ff")
    red = fill("ff0000")
    yield "repeated-blink", [off, purple], [30] * 20
    moving = []
    for zone in range(15):
        zones = bytearray(45)
        zones[zone * 3:zone * 3 + 3] = bytes.fromhex("00ff00")
        moving.append(bytes(zones))
    yield "moving-dot", moving, [3] * 30
    fade = []
    for step in range(17):
        value = step * 255 // 16
        fade.append(bytes([255 - value, 0, value]) * 15)
    yield "two-color-fade", fade, [2] * 34
    gradient = []
    for phase in range(6):
        zones = bytearray()
        for zone in range(15):
            zones.extend(((zone * 17 + phase * 11) & 0xFF, (zone * 7 + phase * 13) & 0xFF, (zone * 3 + phase * 19) & 0xFF))
        gradient.append(bytes(zones))
    yield "spatial-gradient", gradient, [4] * 24
    many = []
    for phase in range(10):
        zones = bytearray()
        for zone in range(15):
            index = phase * 15 + zone
            zones.extend(((index * 5) & 0xFF, (index * 11) & 0xFF, (index * 17) & 0xFF))
        many.append(bytes(zones))
    yield "many-color", many, [2] * 40
    randomizer = random.Random(800)
    random_frames = [bytes(randomizer.randrange(256) for _ in range(45)) for _ in range(24)]
    yield "random-frames", random_frames, [1] * 48


def measure(name, frames, durations):
    return measure_model(name, model(frames, durations))


def measure_model(name, animation):
    sizes = {}
    for codec in CODECS:
        try:
            data = encode_brightness_candidate(animation, codec)
        except CodecUnavailable:
            sizes[codec] = None
            continue
        decoded_frames, entries, loop, end = decode_animation(data)
        expected = [(animation.frames[entry.frame], entry.duration) for entry in animation.entries]
        actual = [(decoded_frames[entry.frame], entry.duration) for entry in entries]
        if actual != expected or loop != animation.loop or end != animation.end:
            raise RuntimeError(f"round-trip failed for {name}/{codec}")
        sizes[codec] = len(data)
    winner = min((codec for codec in CODECS if sizes[codec] is not None), key=lambda codec: (sizes[codec], CODECS.index(codec)))
    return name, len(animation.frames), len(animation.palette), sizes, winner


def main():
    parser = argparse.ArgumentParser(description="Measured MM800 custom-animation codec comparison")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    lines = [
        "# Measured custom-animation codec comparison",
        "",
        "Generated by `tools/benchmark_custom_animation.py`. Every encoding was also",
        "decoded and compared byte-for-byte with its canonical frames and durations.",
        "Sizes include the complete 32-byte header, palette, frame/delta data, and",
        "timeline. These are compiler results, not hardware capacity claims.",
        "",
        "| Scenario | Unique frames | Colors | Dict raw | Dict palette | Delta raw | Delta palette | Envelope | Winner |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for scenario in scenarios():
        name, frame_count, color_count, sizes, winner = measure(*scenario)
        rendered = {codec: str(sizes[codec]) if sizes[codec] is not None else "n/a" for codec in CODECS}
        lines.append(
            f"| {name} | {frame_count} | {color_count} | {rendered['dictionary-raw']} | "
            f"{rendered['dictionary-palette']} | {rendered['delta-raw']} | {rendered['delta-palette']} | {rendered['brightness-envelope']} | {winner} |"
        )
    firefly_animation = optimize_animation_document(load_animation_document("tests/fixtures/custom_animation/fireflies.json"), timing="round")
    name, frame_count, color_count, sizes, winner = measure_model("fireflies", firefly_animation)
    rendered = {codec: str(sizes[codec]) if sizes[codec] is not None else "n/a" for codec in CODECS}
    lines.append(
        f"| {name} | {frame_count} | {color_count} | {rendered['dictionary-raw']} | "
        f"{rendered['dictionary-palette']} | {rendered['delta-raw']} | {rendered['delta-palette']} | {rendered['brightness-envelope']} | {winner} |"
    )
    lines.extend([
        "",
        "The dictionary wins repeated state reuse and small-palette animations.",
        "Delta encoding can win sparse zone changes, but complete records are chosen",
        "when smaller. Raw remains available above 256 colors.",
        "The fireflies example has 2 base colors but 110 rendered colors; the",
        "envelope stores those base colors and gains rather than every rendered shade.",
        "",
    ])
    result = "\n".join(lines)
    if args.output:
        args.output.write_text(result)
        print(f"wrote={args.output}")
    else:
        print(result, end="")


if __name__ == "__main__":
    main()
